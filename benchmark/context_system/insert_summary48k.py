"""48K Insert summary acceptance on recorded BCP tool feedback.

Agent and summary responses are generated by the tested model. Search/tool
feedback is recorded, so this is not a live-search BCP accuracy evaluation.
Complete requests, responses, generated summaries and source hashes are retained.
"""
from __future__ import annotations

import argparse
import copy
import gzip
import hashlib
import json
import sys
import time
from pathlib import Path

CASES = ("238", "241", "775", "786", "787", "822", "844", "864", "870", "875")
THRESHOLD = 48 * 1024
SUMMARY_SYSTEM = "You are a conversation summarizer. Do NOT continue the conversation or answer any questions in it. Output ONLY the structured summary requested."
SUMMARY_FORMAT = """The messages above are a conversation to summarize. Create a structured context checkpoint summary that another LLM will use to continue the work.
Use this EXACT format:
## Goal
[What is the user trying to accomplish?]
## Constraints & Preferences
- [Constraints, or (none)]
## Progress
### Done
- [x] [Completed work]
### In Progress
- [ ] [Current work]
### Blocked
- [Blockers, if any]
## Key Decisions
- **[Decision]**: [Rationale]
## Next Steps
1. [Ordered next steps]
## Critical Context
- [Evidence and unresolved leads]
Keep each section concise. Preserve exact document IDs, URLs, dates, numbers, the original question, and unresolved leads. Do not invent evidence."""


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def logit_metrics(actual, expected):
    import torch
    difference = (actual.float() - expected.float()).abs()
    if not bool(torch.isfinite(difference).all()):
        raise ValueError("Non-finite logits in numerical validation")
    return {"max_abs": difference.max().item(), "mean_abs": difference.mean().item(),
            "p99_abs": torch.quantile(difference.flatten(), .99).item()}


def native_logit_bounds(native_metrics):
    """Predeclared 2x native batch-shape envelope, never fitted to Insert.

    This follows test_model_forward's native calibration rule. Absolute BF16
    floors alone are invalid for GPT-OSS MXFP4: small rounding differences can
    change MoE routes. This is an end-to-end regression gate, not a KV oracle.
    """
    import math
    floors = {"max_abs": .15, "mean_abs": .02, "p99_abs": .0625}
    if not native_metrics or any(not math.isfinite(m[k]) or m[k] < 0
                                 for m in native_metrics for k in floors):
        raise ValueError("Native numerical calibration must be finite and nonnegative")
    return {k: max(floor, 2 * max(m[k] for m in native_metrics)) for k, floor in floors.items()}


def load_cases(root, case_ids):
    root = Path(root)
    entries = {e["case_id"]: e for e in map(json.loads, (root / "tasks_unique.jsonl").read_text().splitlines())}
    cases = []
    with (root / "trajectories.jsonl").open("rb") as source:
        for case_id in case_ids:
            e = entries[case_id]
            source.seek(e["offset"])
            raw = source.read(e["bytes"])
            if hashlib.sha256(raw).hexdigest() != e["sha256"]:
                raise ValueError(f"Source hash mismatch: {case_id}")
            cases.append((json.loads(raw), e["sha256"]))
    return cases, json.loads((root / "manifest.json").read_text())["tools"]


class History:
    def __init__(self):
        self.messages, self.drop_message, self.insert, self.reposition = [], {}, {}, []
        self.dropped = set()
        self.next_index, self.negative = 0, -1

    def append(self, messages):
        first = self.next_index
        for message in copy.deepcopy(messages):
            message["index"] = self.next_index
            self.next_index += 1
            self.messages.append(message)
        return first

    def active(self):
        return [m for m in self.messages if m["index"] not in self.dropped]

    def payload(self):
        return {"messages": self.messages, "drop_message": self.drop_message,
                    "insert": self.insert, "reposition": self.reposition}

    def commit(self, selected, anchor, trigger, text):
        selected = set(selected)
        if not text.strip() or anchor in selected or trigger in selected:
            raise ValueError("Invalid summary transaction")
        if not selected or not selected.isdisjoint(self.dropped):
            raise ValueError("Summary must cover active history")
        # trigger is the first pending ordinary input; its predecessor has
        # already been computed. The logical anchor must also already be born.
        if trigger <= 0 or anchor >= trigger:
            raise ValueError("Summary requires an already-computed kept suffix")
        self.drop_message.setdefault(str(trigger-1), []).extend(sorted(selected))
        self.insert[str(trigger)] = self.negative
        self.reposition.append(self.negative)
        at = next(i for i, m in enumerate(self.messages) if m["index"] == anchor)
        self.messages.insert(at, {"index": self.negative, "role": "user", "content": text.strip()})
        self.dropped.update(selected)
        self.negative -= 1


def select_summary(messages, owners, keep_recent=20000):
    """Retain a complete recent protocol group and the initial task prefix."""
    counts = [0] * len(messages)
    for owner in owners:
        if 0 <= owner < len(counts):
            counts[owner] += 1
    protected = 0
    while protected < len(messages) and messages[protected]["role"] in ("system", "developer"):
        protected += 1
    if protected < len(messages) and messages[protected]["role"] == "user":
        protected += 1
    cut, total = len(messages), 0
    while cut > protected and total < keep_recent:
        cut -= 1
        total += counts[cut]
    while cut > protected and messages[cut]["role"] == "tool":
        cut -= 1
    if cut <= protected or cut >= len(messages):
        raise ValueError("No complete older protocol groups available for summary")
    return messages[protected:cut], messages[cut]["index"]


def summary_messages(protected, selected):
    transcript = "\n".join(json.dumps(m, ensure_ascii=False) for m in selected)
    return [{"role": "system", "content": SUMMARY_SYSTEM}, {"role": "user", "content": "Task context:\n" + json.dumps(protected, ensure_ascii=False) +
        "\n<conversation>\n" + transcript + "\n</conversation>\n\n" + SUMMARY_FORMAT}]


def process_summary(response):
    choice = response["choices"][0]
    text = (choice["message"].get("content") or "").strip()
    if choice["finish_reason"] == "length" or not all(h in text for h in
            ("## Goal", "## Progress", "## Next Steps", "## Critical Context")):
        raise ValueError("Summary is empty, truncated, or missing required headings")
    return text


def run(args):
    import requests
    from sglang.srt.entrypoints.openai.protocol import Tool
    from sglang.srt.parser.gpt_oss_encoding import HarmonyEncoder
    from summary_replay import wire_history

    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=False)
    session = requests.Session()
    session.trust_env = False
    cases, tools = load_cases(args.data, args.cases)
    tools = [Tool.model_validate(t).model_dump() for t in tools]
    serial, results = 0, []
    journal = (out / "events.jsonl").open("a", buffering=1)

    def emit(event):
        journal.write(json.dumps(event, ensure_ascii=False) + "\n")
        print(json.dumps({k: v for k, v in event.items() if k != "response"}), flush=True)

    def call(payload, label):
        nonlocal serial
        serial += 1
        filename = f"{serial:05d}-{label}.json.gz"
        start = time.monotonic()
        response = session.post(args.url + "/v1/chat/completions", json={
            "model": args.model, "temperature": 0, "return_meta_info": True,
            "return_input_ids_in_sglext": True, "return_output_ids_in_sglext": True,
            **payload}, timeout=args.timeout)
        try:
            body = response.json()
        except ValueError:
            body = {"error": response.text}
        record = {"request": payload, "response": body, "status": response.status_code,
                      "seconds": time.monotonic()-start, "request_sha256": digest(payload)}
        with gzip.open(out / filename, "wt") as target:
            json.dump(record, target, ensure_ascii=False)
        if response.status_code != 200:
            raise RuntimeError(f"HTTP {response.status_code}: {body}")
        emit({"kind": "request", "label": label, "artifact": filename, "seconds": record["seconds"],
                  "usage": body.get("usage"), "input_sha256": digest(body.get("sglext", {}).get("input_ids"))})
        return body

    def render(messages):
        clean = [{k: v for k, v in m.items() if k != "index"} for m in messages]
        clean, _ = wire_history(clean)
        ids, owners, _ = HarmonyEncoder("low").render_tokens(clean, tools)
        return ids, owners

    def compare_summary(payload, active_messages, label):
        """Freeze this event's text/tokens and compare warm/exact/cold logits."""
        import torch
        sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "test/registered/context_system"))
        from serving_logits_probe import serialized_probe
        logits, hashes, usage = {}, {}, {}
        def probe_call(request, name):
            path = (out / f"{label}-{name}.pt").resolve()
            probe = dict(request, max_tokens=1, custom_logit_processor=serialized_probe(),
                         custom_params={"context_trace_path": str(path), "context_trace_count": 1})
            response = call(probe, label+"-"+name)
            return response, torch.load(path, weights_only=True)

        for mode in ("warm", "exact"):
            response, logits[mode] = probe_call(payload, mode)
            hashes[mode] = digest(response["sglext"]["input_ids"])
            usage[mode] = response["usage"]
        # Keep the real warm result before flushing. Calibrate only against
        # ordinary native requests, then fix bounds before comparing Insert.
        # Active text is a rounding control, never the semantic KV reference.
        native = {k: v for k, v in payload.items() if k not in
                  ("drop_message", "insert", "reposition", "messages")}
        native["messages"] = [{k: v for k, v in m.items() if k != "index"} for m in active_messages]
        native["messages"], _ = wire_history(native["messages"])
        session.post(args.url + "/flush_cache", timeout=30).raise_for_status()
        probe_call(dict(native, messages=native["messages"][:-1]), "native-source")
        nw, na = probe_call(native, "native-warm")
        ne, nb = probe_call(native, "native-exact")
        session.post(args.url + "/flush_cache", timeout=30).raise_for_status()
        nc, reference = probe_call(native, "native-cold")
        if len({digest(r["sglext"]["input_ids"]) for r in (nw, ne, nc)}) != 1:
            raise ValueError("Native calibration changed tokens")
        calibration = [logit_metrics(x, reference) for x in (na, nb)]
        bounds = native_logit_bounds(calibration)
        emit({"kind": "native_calibration", "label": label, "metrics": calibration, "bounds": bounds})
        session.post(args.url + "/flush_cache", timeout=30).raise_for_status()
        response, logits["cold"] = probe_call(payload, "cold")
        hashes["cold"] = digest(response["sglext"]["input_ids"])
        usage["cold"] = response["usage"]
        if len(set(hashes.values())) != 1:
            raise ValueError("Frozen Insert replay changed execution tokens")
        for mode in ("warm", "exact"):
            metrics = logit_metrics(logits[mode], logits["cold"])
            emit({"kind": "summary_numeric", "label": label, "mode": mode, "metrics": metrics, "bounds": bounds, "usage": usage[mode]})
            if any(metrics[k] > bounds[k] for k in bounds):
                raise ValueError(f"Insert numerical mismatch: {label} {mode} {metrics}")

    for case, source_hash in cases:
        state, summaries = History(), 0
        case_id = case["case_id"]
        session.post(args.url + "/flush_cache", timeout=30).raise_for_status()
        emit({"kind": "case_start", "case_id": case_id, "source_sha256": source_hash})
        try:
            for turn in case["turns"]:
                inserted = False
                trigger = state.append(turn["new_messages"])
                active = state.active()
                ids, owners = render(active)
                if len(ids) >= THRESHOLD:
                    selected, anchor = select_summary(active, owners, args.keep_recent)
                    response = call({"messages": summary_messages(active[:1], selected),
                        "max_tokens": args.summary_tokens, "reasoning_effort": "low"}, f"{case_id}-summary-{summaries}")
                    text = process_summary(response)
                    candidate = copy.deepcopy(state)
                    candidate.commit([m["index"] for m in selected], anchor, trigger, text)
                    active_ids, _ = render(candidate.active())
                    if len(active_ids) >= THRESHOLD:
                        raise ValueError("Processed summary did not reduce active input below 48K")
                    state = candidate
                    summaries += 1
                    inserted = True
                    emit({"kind": "summary_commit", "case_id": case_id, "turn": turn["turn"],
                              "before_tokens": len(ids), "after_tokens": len(active_ids),
                              "anchor": anchor, "trigger": trigger, "summary_sha256": digest(text)})
                payload = copy.deepcopy(state.payload())
                payload["messages"], changes = wire_history(payload["messages"])
                if changes:
                    emit({"kind": "argument_wrapper", "case_id": case_id, "turn": turn["turn"], "changes": changes})
                payload.update(tools=tools, max_tokens=args.probe_tokens or turn["max_new_tokens"],
                               ignore_eos=True, reasoning_effort="low")
                if inserted and not args.skip_numeric:
                    compare_summary(payload, state.active(), f"{case_id}-event-{summaries}")
                body = call(payload, f"{case_id}-turn-{turn['turn']}")
                assistant = body["choices"][0]["message"]
                state.append([assistant])
            if not summaries:
                raise ValueError("Case never triggered a 48K summary")
            result = {"case_id": case_id, "status": "completed", "summaries": summaries, "turns": len(case["turns"])}
        except (requests.RequestException, ValueError, RuntimeError, KeyError) as exc:
            result = {"case_id": case_id, "status": "failed", "summaries": summaries, "error": repr(exc)}
        results.append(result)
        emit(dict(kind="case_end", **result))
        (out / "report.json").write_text(json.dumps({
            "workload": "generated agent and summary, recorded tool feedback",
            "probe_tokens": args.probe_tokens, "model": args.model, "threshold": THRESHOLD,
            "results": results}, indent=2))
    journal.close()
    if any(r["status"] != "completed" for r in results):
        raise SystemExit(1)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument("--data", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--cases", nargs="+", default=list(CASES))
    parser.add_argument("--keep-recent", type=int, default=20000)
    parser.add_argument("--summary-tokens", type=int, default=4096)
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument("--probe-tokens", type=int, default=0,
                        help="Diagnostic budget override; zero uses original per-turn budgets")
    parser.add_argument("--skip-numeric", action="store_true", help="Skip frozen warm/exact/cold logit checks")
    run(parser.parse_args())
